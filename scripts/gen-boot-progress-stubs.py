#!/usr/bin/env python3
"""Regenerate package/BootProgressStubs.c: weak stand-ins for the sheng-only diagnostics that the boot progress kit reads.

  gen-boot-progress-stubs.py UNDEFINED.txt     (one symbol per line, without the leading underscore)

BootProgress.c and BootLog.c read counters and call helpers of sheng's display, HID, touch, Adreno and cpufreq code through weak_import
declarations. The kernel link (ld64, static) still needs a definition for each, so every symbol the link reports undefined gets a weak one:
functions keep their declared signature and return zero, data is 4 KiB of zeros (larger than any declared array). A real definition, once
linked (the display and touch archives), takes precedence. Pass the undefined symbols of a failed link; the existing stubs are kept."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / 'package'
OUT = PACKAGE / 'BootProgressStubs.c'


def declarations():
    """name -> (return type, parameter list) for every function declared extern in the kit's C sources."""
    result = {}
    for source in sorted(PACKAGE.glob('*.c')):
        for match in re.finditer(r'^\s*extern\s+([^;()]*?)\b(\w+)\s*\(([^;()]*(?:\([^()]*\)[^;()]*)*)\)\s*(?:__attribute__\(\(\w+\)\)\s*)?;',
                                 source.read_text(), re.M):
            kind, name, params = match.group(1).strip(), match.group(2), match.group(3).strip()
            if '(*' not in kind and not kind.startswith('"'):
                result.setdefault(name, (re.sub(r'\s+', ' ', kind.replace('__attribute__((weak_import))', '')).strip(), params))
    return result


def existing():
    if not OUT.is_file():
        return []
    return re.findall(r'^__attribute__\(\(weak[^)]*\)\) (.*)$', OUT.read_text(), re.M)


def main():
    wanted = set(Path(sys.argv[1]).read_text().split()) if len(sys.argv) > 1 else set()
    functions = declarations()
    lines = {}
    for line in existing():
        name = re.search(r'(\w+)\s*(?:\[|\()', line).group(1)
        lines[name] = line
    for name in sorted(wanted):
        if name in functions:
            kind, params = functions[name]
            names = [p.strip().split()[-1].strip('*').split('[')[0] for p in params.split(',') if p.strip() and p.strip() != 'void']
            # Unnamed parameters: give each a placeholder name so the definition is valid C.
            typed = []
            for index, param in enumerate([p.strip() for p in params.split(',') if p.strip()]):
                if param == 'void':
                    typed.append('void')
                elif '[' in param and '(' not in param:
                    typed.append(param if re.search(r'\w+\s*\[', param.split('[', 1)[0] + '[') and len(param.split('[')[0].split()) > 1
                                 else param.replace('[', f'p{index}[', 1))
                elif len(param.replace('*', ' * ').split()) == 1 or param.endswith('*') or param in ('unsigned', 'int', 'uint32_t', 'uint64_t', 'size_t', 'unsigned long'):
                    typed.append(f'{param} p{index}')
                else:
                    typed.append(param)
            body = '{}' if kind == 'void' else '{ return 0; }'
            uses = ' '.join(f'(void)p{i};' for i in range(len(typed)) if typed[i] != 'void' and f'p{i}' in typed[i])
            lines[name] = f'{kind} {name}({", ".join(typed) or "void"}) {{ {uses} {body[1:-1].strip()} }}'.replace('{  }', '{}')
        else:
            lines.setdefault(name, f'char {name}[4096] __attribute__((aligned(16)));')
    out = ['// SPDX-License-Identifier: BSD-2-Clause-Patent',
           "// Weak stand-ins for the diagnostics the boot progress kit reads from sheng's display, HID, touch, Adreno and cpufreq code, which",
           '// fajita does not link (yet). Data reads as zero and functions return zero; a real definition, once linked, takes precedence.',
           '// Generated by scripts/gen-boot-progress-stubs.py from the undefined symbols of the fajita kernel link.',
           '#include <stdint.h>', '#include <stddef.h>', '']
    out += [f'__attribute__((weak)) {lines[name]}' for name in sorted(lines)]
    OUT.write_text('\n'.join(out) + '\n')
    print(f'{len(lines)} stubs ({sum(1 for n in lines if n in functions)} functions)')


if __name__ == '__main__':
    main()
